-- ===== INITIALIZE LANGUAGE FUNCTION =====
function ProChat.Locales:InitializeLanguage()
    if ProChatDB and ProChatDB.lang then return end
    
    local clientLocale = _G.GetLocale()
    if clientLocale == "esES" or clientLocale == "esMX" then
        ProChatDB.lang = "es"
    else
        ProChatDB.lang = "en"
    end
end

